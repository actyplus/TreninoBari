create table if not exists public.consents (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  policy_version text not null check (char_length(policy_version) between 1 and 20),
  privacy_accepted boolean not null default false,
  community_rules_accepted boolean not null default false,
  age_declaration text not null check (age_declaration in ('14_or_parental_authorization')),
  accepted_at timestamptz not null default now(),
  user_agent text check (user_agent is null or char_length(user_agent) <= 300),
  unique (user_id, policy_version)
);

create table if not exists public.privacy_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  request_type text not null check (request_type in ('access','rectification','export','restriction','deletion')),
  details text not null check (char_length(details) between 5 and 500),
  status text not null default 'received' check (status in ('received','processing','completed','rejected')),
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

