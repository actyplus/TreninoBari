drop policy if exists "users update own posts" on public.posts;
create policy "users update own posts" on public.posts for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "users delete own posts" on public.posts;
create policy "users delete own posts" on public.posts for delete using (auth.uid() = user_id);

drop policy if exists "comments readable by everyone" on public.comments;
create policy "comments readable by everyone" on public.comments for select using (deleted_at is null);
drop policy if exists "users create own comments" on public.comments;
create policy "users create own comments" on public.comments for insert with check (auth.uid() = user_id);
drop policy if exists "users edit own comments" on public.comments;
create policy "users edit own comments" on public.comments for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "users delete own comments" on public.comments;
create policy "users delete own comments" on public.comments for delete using (auth.uid() = user_id);

drop policy if exists "reactions readable by everyone" on public.post_reactions;
create policy "reactions readable by everyone" on public.post_reactions for select using (true);
drop policy if exists "users create own reactions" on public.post_reactions;
create policy "users create own reactions" on public.post_reactions for insert with check (auth.uid() = user_id);
drop policy if exists "users delete own reactions" on public.post_reactions;
create policy "users delete own reactions" on public.post_reactions for delete using (auth.uid() = user_id);

drop policy if exists "predictions readable by everyone" on public.predictions;
create policy "predictions readable by everyone" on public.predictions for select using (true);
drop policy if exists "users create own predictions" on public.predictions;
create policy "users create own predictions" on public.predictions for insert with check (auth.uid() = user_id);
drop policy if exists "users update own predictions" on public.predictions;
create policy "users update own predictions" on public.predictions for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "users create reports" on public.reports;
create policy "users create reports" on public.reports for insert with check (auth.uid() = reporter_id);
